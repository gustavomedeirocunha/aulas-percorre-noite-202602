// Declarar uma variavel chamada contador que recebe um valor numerico
let contador = 0;

// Enquanto contador for menor do que 10 repita
while (contador <= 10) {
  console.log("OLHA A HORA DO CAFÉ");
  console.log("VENHA TOMAR CAFÉ");
  console.log("CAFÉ DA MANHÃ, CAFÉ DA TARDE! NÃO IMPORTA");
  console.log("VENHA TOMAR CAFÉ");

  // Adicionar ++ após o nome de uma variavel faz com que seja adicionado 1 ao seu valor
  contador++;
  console.log(contador);
}
